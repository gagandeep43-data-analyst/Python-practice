# Arithmetic Operators
a=10
b=5


print(a+b)
print("Subtraction:",a-b)
print("Multiplication:",a*b)
print("Divison:",a/b)
print("Modules:",a*b)
print("Exponent:",a**b)
print("Floor Divison",a//b)


#Comparison Operators
print("a>b:",a>b)
print("a<b:",a<b)
print("a==b:",a==b)
print("a!=b:",a!=b)


#Logical Operators
x=True
y=False


print("x and y:",x and y)
print("x or y:",x or y)
print("notx:", not x)