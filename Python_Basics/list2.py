items=["Milk","Bread","Egg","Rice","Milk"]
print(items)

#indexing
print(items[2])
print(items[-2])

#slicing
print(items[2:])
print(items[-3:])

#update
items[1]="Butter"
print(items)

#add elements
items.append("Suger")
print(items)

items.extend(["Soap","Oil"])
print(items)


