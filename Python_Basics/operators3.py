#Arithmetic Operator
a=10
b=5
print("Addition:",a+b)
print("subtraction:",a-b)
print("Multiplication:",a*b)
print("Division:",a/b)
print("Modulus:",a%b)
print("Floor Division:",a//b)

#Comparison Operators
print("a>b:",a>b)
print("a<b:",a<b)
print("a==b:",a==b)
print("a!=b:",a!=b)

#LogicalOperation
x=True
y=False

print("x and y:",x and y)
print("x or y:",x or y)
print("not x:",not x)
